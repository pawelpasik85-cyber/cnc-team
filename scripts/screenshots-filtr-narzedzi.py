import sys
from playwright.sync_api import sync_playwright
base, out = sys.argv[1], sys.argv[2]; errors=[]
with sync_playwright() as p:
    b=p.chromium.launch()
    ctx=b.new_context(viewport={"width":412,"height":915},device_scale_factor=2,is_mobile=True,has_touch=True,locale="pl-PL")
    pg=ctx.new_page(); pg.on("pageerror",lambda e: errors.append(str(e)))
    pg.goto(base+"/"); pg.fill("input[name=login]","adam"); pg.fill("input[name=password]","demo-cnc-2026"); pg.click("button[type=submit]"); pg.wait_for_selector("main")
    pg.goto(base+"/#/narzedzia?rodzaj=frez"); pg.wait_for_selector("#tlTyp")
    pg.select_option("#tlTyp", "fazownik"); pg.wait_for_timeout(800)
    n = pg.locator(".tl-row").count()
    if n != 1 or "Fazownik" not in pg.inner_text(".tl-list"): errors.append(f"filtr fazownik: {n}")
    pg.screenshot(path=f"{out}/152-tel-filtr-rodzaj.png")
    pg.select_option("#tlTyp", "gwintownik"); pg.wait_for_timeout(800)
    if "Gwintownik" not in pg.inner_text(".tl-list") or "Frez do gwintów" in pg.inner_text(".tl-list"): errors.append("filtr gwintownik")
    pg.click(".section-tabs a[href*='rodzaj=oprawka']"); pg.wait_for_timeout(800)
    if "typ=" in pg.url: errors.append("filtr rodzaju nie wyczyszczony przy zmianie zakładki")
    pg.select_option("#tlTyp", "termo"); pg.wait_for_timeout(800)
    if pg.locator(".tl-row").count() != 3: errors.append("filtr termo: %d" % pg.locator(".tl-row").count())
    ctx.close()
    ctx=b.new_context(viewport={"width":1440,"height":1000},locale="pl-PL"); pg=ctx.new_page(); pg.on("pageerror",lambda e: errors.append(str(e)))
    pg.goto(base+"/"); pg.fill("input[name=login]","kierownik"); pg.fill("input[name=password]","demo-cnc-2026"); pg.click("button[type=submit]"); pg.wait_for_selector("main")
    pg.goto(base+"/#/narzedzia?rodzaj=frez"); pg.wait_for_selector("#addTool"); pg.click("#addTool"); pg.wait_for_selector("dialog[open]")
    pg.fill("dialog[open] input[name=name]", "Gwintownik M10 maszynowy"); pg.select_option("dialog[open] select[name=p_type]", "gwintownik"); pg.wait_for_timeout(200)
    if not pg.locator("dialog[open] select[name=p_hole]").is_visible(): errors.append("brak pola otworów")
    pg.select_option("dialog[open] select[name=p_hole]", "przelotowe")
    pg.fill("dialog[open] input[name=p_D]", "10"); pg.fill("dialog[open] input[name=p_pitch]", "1.5"); pg.fill("dialog[open] input[name=p_Lc]", "20"); pg.fill("dialog[open] input[name=p_L]", "90")
    pg.screenshot(path=f"{out}/153-gwintownik-formularz.png")
    pg.click("dialog[open] button[type=submit]"); pg.wait_for_timeout(900)
    if pg.locator("dialog[open]").count(): errors.append("nie zapisano: " + pg.inner_text("dialog[open] .form-error"))
    pg.goto(base+"/#/narzedzia?rodzaj=frez&typ=gwintownik"); pg.wait_for_timeout(800)
    if "otw. przelotowe" not in pg.inner_text(".tl-list") or "otw. nieprzelotowe" not in pg.inner_text(".tl-list"): errors.append("brak rodzaju otworu w wierszu")
    pg.screenshot(path=f"{out}/154-gwintowniki-lista.png")
    b.close()
print("\n".join(errors) or "OK")
